const escapeRegExp = (value: string) =>
  value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const retainOuterWhitespace = (input: string, translated: string) => {
  const leading = input.match(/^\s*/)?.[0] ?? "";
  const trailing = input.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
};

export const getStoredInterfaceLanguage = (): InterfaceLanguage =>
  window.localStorage.getItem(interfaceLanguageStorageKey) === "EN" ? "EN" : "ES";

export function translateInterfaceText(
  input: string,
  language: InterfaceLanguage = getStoredInterfaceLanguage(),
) {
  if (!input || !/[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]/.test(input)) return input;
  const trimmed = input.trim();
  if (!trimmed) return input;

  const exact = language === "EN"
    ? exactSpanish.get(trimmed.toLocaleLowerCase("es-MX"))
    : exactEnglish.get(trimmed.toLocaleLowerCase("en-US"));
  if (exact) return retainOuterWhitespace(input, exact);

  let translated = trimmed;
  for (const [spanish, english] of orderedPairs) {
    const source = language === "EN" ? spanish : english;
    const target = language === "EN" ? english : spanish;
    if (source.length < 3 || source === target) continue;
    const pattern = new RegExp(`(?<![\\p{L}\\p{N}])${escapeRegExp(source)}(?![\\p{L}\\p{N}])`, "giu");
    translated = translated.replace(pattern, target);
  }
  for (const [spanish, english] of connectorPairs) {
    const source = language === "EN" ? spanish : english;
    const target = language === "EN" ? english : spanish;
    translated = translated.replace(new RegExp(escapeRegExp(source), "giu"), target);
  }
  return retainOuterWhitespace(input, translated);
}

export const translateInterfaceRecord = <T extends Record<string, unknown>>(
  record: T,
  language: InterfaceLanguage = getStoredInterfaceLanguage(),
) => Object.fromEntries(
  Object.entries(record).map(([key, value]) => [
    translateInterfaceText(key, language),
    typeof value === "string" ? translateInterfaceText(value, language) : value,
  ]),
);

interface TranslationState {
  source: string;
  last: string;
}

const textStates = new WeakMap<Text, TranslationState>();
const attributeStates = new WeakMap<Element, Map<string, TranslationState>>();
const translatedAttributes = ["aria-label", "placeholder", "title", "data-placeholder"] as const;
let activeLanguage: InterfaceLanguage = "ES";
let translationObserver: MutationObserver | null = null;

const translateTextNode = (node: Text) => {
  const current = node.nodeValue ?? "";
  let state = textStates.get(node);
  if (!state || current !== state.last) {
    state = { source: current, last: current };
    textStates.set(node, state);
  }
  const next = translateInterfaceText(state.source, activeLanguage);
  state.last = next;
  if (current !== next) node.nodeValue = next;
};

const translateElementAttributes = (element: Element) => {
  let states = attributeStates.get(element);
  if (!states) {
    states = new Map();
    attributeStates.set(element, states);
  }
  translatedAttributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    const current = element.getAttribute(attribute) ?? "";
    let state = states!.get(attribute);
    if (!state || current !== state.last) {
      state = { source: current, last: current };
      states!.set(attribute, state);
    }
    const next = translateInterfaceText(state.source, activeLanguage);
    state.last = next;
    if (current !== next) element.setAttribute(attribute, next);
  });
};

const translateTree = (root: Node) => {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root as Text);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
  if (root.nodeType === Node.ELEMENT_NODE) translateElementAttributes(root as Element);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) translateTextNode(current as Text);
    else translateElementAttributes(current as Element);
    current = walker.nextNode();
  }
};

const ensureTranslationObserver = () => {
  if (translationObserver || !document.body) return;
  translationObserver = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData") translateTextNode(mutation.target as Text);
      if (mutation.type === "attributes") translateElementAttributes(mutation.target as Element);
      mutation.addedNodes.forEach(translateTree);
    });
  });
  translationObserver.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...translatedAttributes],
  });
};

export function useGlobalInterfaceTranslation(language: InterfaceLanguage) {
  useLayoutEffect(() => {
    activeLanguage = language;
    document.documentElement.lang = language === "EN" ? "en" : "es-MX";
    window.localStorage.setItem(interfaceLanguageStorageKey, language);
    translateTree(document.body);
    ensureTranslationObserver();
  }, [language]);
}
